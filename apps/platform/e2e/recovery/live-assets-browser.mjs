import { chromium, expect } from '@playwright/test'
const base = process.env.RECOVERY_UI_URL || 'http://demo.localhost:3002'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(base + '/login')
  await page.locator('input[type=email]').fill('owner@unifiedtree.demo')
  await page.locator('input[type=password]').fill(process.env.RECOVERY_PASSWORD || 'Hrms@12345')
  await page.locator('button[type=submit]').click()
  await page.waitForURL(url => !url.pathname.includes('login'), { timeout: 60000 })
  await page.goto(base + '/hrms/onboarding/instances')
  await page.getByRole('tab', { name: /Asset/ }).click()
  await page.getByRole('button', { name: 'Register asset' }).click()
  const tag = `UI-${Date.now()}`
  const form = page.locator('form')
  await form.getByLabel('Asset company').selectOption({ index: 1 })
  await form.getByLabel('Asset tag', { exact: true }).fill(tag)
  await form.getByLabel('Category', { exact: true }).fill('Laptop')
  await form.getByLabel('Asset name', { exact: true }).fill('UI verification laptop')
  await form.getByRole('button', { name: 'Save asset' }).click()
  const row = page.getByRole('row').filter({ hasText: tag })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Assign', exact: true }).click()
  const action = page.getByRole('region', { name: 'Asset action' })
  await action.getByLabel('Find employee').fill('admin@unifiedtree.demo')
  await action.getByRole('button', { name: /Admin User/ }).click()
  await action.getByRole('button', { name: 'Confirm assignment' }).click()
  await expect(row.getByRole('button', { name: 'Receive return' })).toBeVisible()
  await row.getByRole('button', { name: 'Receive return' }).click()
  await action.getByLabel('Condition on return').fill('Intact after UI verification')
  await action.getByRole('button', { name: 'Record return' }).click()
  await expect(row.getByText('RETURNED', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('tab', { name: /Asset/ }).click()
  await expect(page.getByRole('row').filter({ hasText: tag }).getByText('Intact after UI verification')).toBeVisible()
  await row.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Asset allocation history' })).toContainText('Admin User')
  await expect(page.getByRole('region', { name: 'Asset allocation history' })).toContainText('Returned')
  await page.goto(base + '/hrms/compliance')
  await expect(page.getByRole('region', { name: 'Filing calendar' })).toBeVisible()
  await page.getByRole('button', { name: 'Next month' }).click()
  await page.getByRole('button', { name: 'Previous month' }).click()
  expect(errors).toEqual([])
  console.log('PASS asset registration, assignment, return and persisted reload; calendar navigation')
} finally { await browser.close() }
