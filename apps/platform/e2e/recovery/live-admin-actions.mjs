import { chromium, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
const base = process.env.RECOVERY_UI_URL || 'http://demo.localhost:3002'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
mkdirSync('test-results/recovery', { recursive: true })
try {
  await page.goto(base + '/login')
  await page.locator('input[type=email]').fill('owner@unifiedtree.demo')
  await page.locator('input[type=password]').fill(process.env.RECOVERY_PASSWORD || 'Hrms@12345')
  await page.locator('button[type=submit]').click()
  await page.waitForURL(url => !url.pathname.includes('login'))
  await page.goto(base + '/dashboard')
  await page.getByRole('heading', { name: 'Live overview', exact: true }).waitFor()
  await page.keyboard.press('Control+k')
  await page.getByRole('combobox', { name: 'Search people, pages and actions' }).fill('Reader')
  await page.getByRole('option').filter({ hasText: 'Reader User' }).click()
  await expect(page).toHaveURL(/\/hrms\/employees\/22222222-2222-2222-2222-222222222222/)
  console.log('PASS: preserved global search finds the employee through the live API and opens their profile')
  await page.getByRole('button', { name: 'Change shift', exact: true }).click()
  const shift = page.getByLabel('New shift')
  await expect(shift).toBeVisible()
  const options = await shift.locator('option').allTextContents()
  const current = await page.getByText('Current shift', { exact: true }).locator('..').innerText()
  const choice = options.find(o => o !== 'Select a shift' && !current.includes(o.split(' · ')[0]))
  await shift.selectOption({ label: choice })
  const saveButton = page.getByRole('button', { name: 'Save shift', exact: true })
  await expect(saveButton).toBeEnabled()
  const [saved] = await Promise.all([page.waitForResponse(r => r.url().includes('/v1/shifts/employee/') && r.request().method() === 'POST'), saveButton.click()])
  expect(saved.status()).toBe(200)
  await expect(page.getByRole('heading', { name: 'Change employee shift' })).toBeHidden()
  await page.reload()
  await page.getByRole('button', { name: 'Change shift', exact: true }).click()
  await expect(page.getByText(choice.split(' · ')[0], { exact: true }).last()).toBeVisible()
  await page.screenshot({ path: 'test-results/recovery/employee-shift-live.png', fullPage: true })
  console.log('PASS: company owner changes shift through the UI and sees it after reload')
  await page.goto(base + '/dashboard')
  await page.getByRole('button', { name: /Late arrivals/ }).click()
  await expect(page).toHaveURL(/status=LATE.*date=/)
  await expect(page.getByText('Reader User', { exact: true }).last()).toBeVisible()
  await page.screenshot({ path: 'test-results/recovery/late-employee-live.png', fullPage: true })
  console.log('PASS: real dashboard late count opens the named employee on the same date')
} finally { await browser.close() }
